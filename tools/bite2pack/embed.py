#!/usr/bin/env python3
"""Write flow/src/xf_embedded.rs: the list of pack files compiled into flow
with the cargo feature `goat-transformers`.

    tools/bite2pack/embed.py [--check]

The list is every `flow/xf/model/*.def` (`core.def` first) and every
`flow/xf/packs/*/pack.def`, with `flow/xf/index.json`. `--check` writes
nothing and exits 1 when the file is not what would be written. Python 3
standard library only.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
XF = ROOT / "flow" / "xf"
OUT = ROOT / "flow" / "src" / "xf_embedded.rs"


def render() -> str:
    models = sorted(XF.glob("model/*.def"), key=lambda p: (p.name != "core.def", p.name))
    packs = sorted(XF.glob("packs/*/pack.def"))
    if not models or models[0].name != "core.def" or not packs:
        sys.exit(f"{XF}: expected model/core.def and at least one packs/*/pack.def")

    def lines(paths):
        return "".join(f'    include_str!("../xf/{p.relative_to(XF).as_posix()}"),\n' for p in paths)

    return (
        "//! The packs compiled into the `xf` transform: the files of `flow/xf`.\n"
        "//! GENERATED by tools/bite2pack/embed.py; run tools/bite2pack/refresh.sh.\n"
        "\n"
        "/// Model modules, `core` first.\n"
        f"pub(crate) const MODELS: &[&str] = &[\n{lines(models)}];\n"
        "\n"
        "/// One pack per format.\n"
        f"pub(crate) const PACKS: &[&str] = &[\n{lines(packs)}];\n"
        "\n"
        "/// Which pack was generated for which dictionary and interface.\n"
        'pub(crate) const INDEX: &str = include_str!("../xf/index.json");\n'
    )


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is out of date; run tools/bite2pack/refresh.sh", file=sys.stderr)
            return 1
        print(f"check: {OUT.relative_to(ROOT)} lists the files of flow/xf")
        return 0
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
