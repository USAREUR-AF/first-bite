#!/usr/bin/env python3
"""Write flow/src/xf_embedded.rs: the list of pack files compiled into flow
with the cargo feature `goat-transformers`.

    tools/bite2pack/embed.py [--check]
    tools/bite2pack/embed.py --used-models <goat-transformers checkout> <pack path>...

The list is every `flow/xf/model/*.def` (`core.def` first, and each module
after the modules it uses) and every `flow/xf/packs/*/pack.def`, with
`flow/xf/index.json`. A `uses` line of a pack or module that names no module
of flow/xf stops it. `--check` writes nothing and exits 1 when the file is not
what would be written.

`--used-models` prints the model modules that the named packs of a checkout
use: `core`, every module their `uses` lines name, and the modules those use in
turn. refresh.sh --upstream copies these with the packs, so a pack that begins
to use a new module brings it along. Python 3 standard library only.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
XF = ROOT / "flow" / "xf"
OUT = ROOT / "flow" / "src" / "xf_embedded.rs"


def uses(text: str) -> list:
    """The modules named by the `uses` lines of a pack or model module."""
    return [line.split()[1] for line in text.splitlines() if line.split()[:1] == ["uses"] and len(line.split()) > 1]


def used_models(root: pathlib.Path, packs: list) -> list:
    """`model/<m>.def` for core and every module the packs under root use, directly or not."""
    todo = ["core"] + [m for p in packs for m in uses((root / p).read_text(encoding="utf-8"))]
    seen = set()
    while todo:
        module = todo.pop()
        if module not in seen:
            seen.add(module)
            todo.extend(uses((root / "model" / f"{module}.def").read_text(encoding="utf-8")))
    return [f"model/{m}.def" for m in sorted(seen)]


def missing_modules(xf: pathlib.Path) -> list:
    """Each `uses` of a pack or module under xf that names no module under xf."""
    have = {p.stem for p in xf.glob("model/*.def")}
    out = []
    for path in sorted(xf.glob("packs/*/pack.def")) + sorted(xf.glob("model/*.def")):
        for module in uses(path.read_text(encoding="utf-8")):
            if module not in have:
                out.append(f"{path.relative_to(xf).as_posix()}: uses {module}, and model/{module}.def is not there")
    return out


def model_order(xf: pathlib.Path) -> list:
    """The modules of xf, core first and each after the modules it uses; ties in name order."""
    used = {p.stem: uses(p.read_text(encoding="utf-8")) for p in xf.glob("model/*.def")}
    order = []

    def visit(module, path):
        if module in order:
            return
        if module in path:
            sys.exit(f"{xf}: the model modules use each other in a cycle: {' -> '.join(path + [module])}")
        for u in used[module]:
            visit(u, path + [module])
        order.append(module)

    for module in ["core"] + sorted(used):
        if module in used:
            visit(module, [])
    return [xf / "model" / f"{m}.def" for m in order]


def render(xf: pathlib.Path = XF) -> str:
    missing = missing_modules(xf)
    if missing:
        sys.exit(f"{xf}: " + "; ".join(missing) + ". Run tools/bite2pack/refresh.sh --upstream <checkout>.")
    models = model_order(xf)
    packs = sorted(xf.glob("packs/*/pack.def"))
    if not models or models[0].name != "core.def" or not packs:
        sys.exit(f"{xf}: expected model/core.def and at least one packs/*/pack.def")

    def lines(paths):
        return "".join(f'    include_str!("../xf/{p.relative_to(xf).as_posix()}"),\n' for p in paths)

    return (
        "//! The packs compiled into the `xf` transform: the files of `flow/xf`.\n"
        "//! GENERATED by tools/bite2pack/embed.py; run tools/bite2pack/refresh.sh.\n"
        "\n"
        "/// Model modules, `core` first and each after the modules it uses.\n"
        f"pub(crate) const MODELS: &[&str] = &[\n{lines(models)}];\n"
        "\n"
        "/// One pack per format.\n"
        f"pub(crate) const PACKS: &[&str] = &[\n{lines(packs)}];\n"
        "\n"
        "/// Which pack was generated for which dictionary and interface.\n"
        'pub(crate) const INDEX: &str = include_str!("../xf/index.json");\n'
    )


def main() -> int:
    if sys.argv[1:2] == ["--used-models"]:
        if len(sys.argv) < 4:
            sys.exit("usage: embed.py --used-models <goat-transformers checkout> <pack path>...")
        print("\n".join(used_models(pathlib.Path(sys.argv[2]), sys.argv[3:])))
        return 0
    text = render()
    if "--check" in sys.argv[1:]:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is out of date; run tools/bite2pack/refresh.sh", file=sys.stderr)
            return 1
        print(f"check: {OUT.relative_to(ROOT)} lists the files of flow/xf")
        return 0
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
